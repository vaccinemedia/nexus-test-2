"""Convert the photofit feature art into Z80 data.

    python3 tools/photofit/build_data.py

Writes:
    src/photofit_small.inc    bank 6: interrogation art (8 bytes x 96 rows)
                              and hair-colour cell maps
    src/photofit_select.inc   bank 4: feature selection tables
    src/photofit_large_a.inc  bank 4: dossier head, collar, marks, eyes,
                              brows, nose, mouth (12 bytes x 144 rows)
    src/photofit_large_b.inc  bank 3: dossier facial hair and hair

Each feature becomes two streams over a linear row-major buffer:
    mask stream   ink &= ~m  (and, small face only, sil |= m)
    ink stream    ink |= i
The head's mask stream is always empty: the small face rebuilds the head
silhouette by filling each row between its outermost ink pixels, and the
dossier face is monochrome and has nothing beneath the head to clear.

Stream encoding:
    #00            end
    #01..#7F  n    n literal bytes follow
    #80..#BF  n    skip (n - #7F) bytes, 1..64
    #C0..#FF  n    (n - #BF) bytes of #FF, 1..64
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import features as F
import pfselect

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")

# Category order matches the selection record (pf_sel).
CATS = [("head", len(F.HEADS)), ("collar", len(F.COLLARS)), ("marks", len(F.MARKS)), ("eyes", len(F.EYES)),
        ("brows", len(F.BROWS)), ("nose", len(F.NOSES)), ("mouth", len(F.MOUTHS)), ("facial", len(F.FACIAL)),
        ("hair", len(F.HAIRS))]
assert [c for c, _ in CATS] == pfselect.CAT_ORDER


def pack(layer):
    wb = layer.w // 8
    out = bytearray()
    for y in range(layer.h):
        for xb in range(wb):
            v = 0
            for b in range(8):
                if layer.get(xb * 8 + b, y):
                    v |= 0x80 >> b
            out.append(v)
    return out


def rle(data):
    out = bytearray()
    i, n = 0, len(data)
    while n and data[n - 1] == 0:          # trailing zeros never need encoding
        n -= 1

    def run(j, v, cap):
        k = j
        while k < n and data[k] == v and k - j < cap:
            k += 1
        return k - j

    while i < n:
        z = run(i, 0, 64)
        f = run(i, 0xFF, 64)
        if z:
            out.append(0x7F + z)
            i += z
        elif f >= 2:
            out.append(0xBF + f)
            i += f
        else:
            j = i
            while j < n and j - i < 127 and not (data[j] == 0 or (data[j] == 0xFF and j + 1 < n and data[j + 1] == 0xFF)):
                j += 1
            if j == i:
                j += 1
            out.append(j - i)
            out += data[i:j]
            i = j
    out.append(0)
    return out


def unrle(stream, size):
    buf = bytearray(size)
    i = p = 0
    while stream[i]:
        c = stream[i]
        i += 1
        if c >= 0xC0:
            buf[p:p + c - 0xBF] = b"\xFF" * (c - 0xBF)
            p += c - 0xBF
        elif c & 0x80:
            p += c - 0x7F
        else:
            buf[p:p + c] = stream[i:i + c]
            i += c
            p += c
    return buf


def db_lines(data):
    return ["    DB " + ",".join(f"#{b:02X}" for b in data[k:k + 16]) for k in range(0, len(data), 16)]


def emit_cats(scale, prefix, cats):
    lines, total = [], 0
    for cat in cats:
        n = dict(CATS)[cat]
        lines.append(f"{prefix}_{cat}_tab:")
        for i in range(n):
            lines.append(f"    DW {prefix}_{cat}_{i}_m, {prefix}_{cat}_{i}_i")
    for cat in cats:
        n = dict(CATS)[cat]
        for i in range(n):
            f = F.render_feature(cat, i, scale)
            m, k = pack(f.mask), pack(f.ink)
            if cat == "head":
                m = bytes(len(m))
            for tag, data in (("m", m), ("i", k)):
                s = rle(data)
                assert unrle(s, len(data)) == data
                lines.append(f"{prefix}_{cat}_{i}_{tag}:")
                lines += db_lines(s)
                total += len(s)
    return lines, total


def hair_maps():
    lines = []
    for cat in ("hair", "facial"):
        lines.append(f"pfs_{cat}_cells:          ; 12 rows per variant, bit 7 = column 0")
        for i in range(dict(CATS)[cat]):
            cells = F.hair_cells(cat, i)
            row = [sum(0x80 >> c for c in range(8) if (c, r) in cells) for r in range(12)]
            lines.append("    DB " + ",".join(f"#{b:02X}" for b in row) + f"   ; {i}")
    lines.append("pf_mouth_hidden:          ; per facial variant: 1 = mouth not drawn red")
    lines.append("    DB " + ",".join("1" if i in F.MOUTH_HIDING_FACIAL else "0" for i in range(dict(CATS)["facial"])))
    return lines


def write(name, lines):
    with open(os.path.join(ROOT, "src", name), "w") as fh:
        fh.write("; Auto-generated by tools/photofit/build_data.py — do not edit\n\n")
        fh.write("\n".join(lines) + "\n")


def main():
    small, n_small = emit_cats(1.0, "pfs", [c for c, _ in CATS])
    write("photofit_small.inc", hair_maps() + small)
    write("photofit_select.inc", pfselect.asm_tables())
    a_cats = ["head", "collar", "marks", "eyes", "brows", "nose", "mouth"]
    large_a, n_a = emit_cats(1.5, "pfl", a_cats)
    write("photofit_large_a.inc", large_a)
    large_b, n_b = emit_cats(1.5, "pfl", ["facial", "hair"])
    write("photofit_large_b.inc", large_b)
    print(f"small art {n_small} bytes, large art {n_a} + {n_b} bytes")


if __name__ == "__main__":
    main()
